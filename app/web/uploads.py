"""PDF upload validation, safe file naming, and path containment.

Rules (task 7.4):
- Only PDFs: the file name must end in .pdf and the content must start with
  the %PDF- magic bytes.
- The stored file name is generated by us (from the DOI or paper id), never
  taken from the upload, so path traversal through the name is impossible.
- Files live only directly under data/pdfs/. The DB stores just the bare file
  name, and serving resolves it back inside data/pdfs/ with a containment check.
"""

from __future__ import annotations

import os
import re
import tempfile
from pathlib import Path
from typing import BinaryIO

PDF_MAGIC = b"%PDF-"
MAX_PDF_BYTES = 100 * 1024 * 1024  # 100 MB
_CHUNK = 1024 * 1024
_UNSAFE_CHARS = re.compile(r"[^A-Za-z0-9._-]+")
_MAX_STEM = 120
# Windows reserved device names cannot be used as file names.
_WINDOWS_RESERVED = {
    "con", "prn", "aux", "nul",
    *(f"com{i}" for i in range(1, 10)),
    *(f"lpt{i}" for i in range(1, 10)),
}


class UploadError(ValueError):
    """Raised with a Japanese message suitable for showing to the user."""


def safe_pdf_filename(doi: str | None, paper_id: int) -> str:
    """Build the stored file name, e.g. '10.1021_jacs.5b00001.pdf'.

    Follows design section 4: data/pdfs/<DOI made file-name safe>.pdf, with a
    'paper-<id>' fallback when there is no DOI.
    """
    stem = ""
    if doi:
        stem = _UNSAFE_CHARS.sub("_", doi.strip())
        stem = stem.strip("._-")[:_MAX_STEM].rstrip("._-")
    if not stem or stem.lower().split(".")[0] in _WINDOWS_RESERVED:
        stem = f"paper-{int(paper_id)}"
    return f"{stem}.pdf"


def check_pdf_filename(filename: str | None) -> None:
    """Validate the uploader's original file name has a .pdf extension.

    The name is only inspected, never used for storage.
    """
    if not filename or not filename.strip().lower().endswith(".pdf"):
        raise UploadError("PDF ファイル（.pdf）だけ登録できます。")


def resolve_pdf_path(pdf_dir: Path, name: str | None) -> Path | None:
    """Map a stored file name to a path inside pdf_dir, or None if unsafe.

    Rejects anything with a directory component, '..', a drive, or a non-.pdf
    suffix, then double-checks the resolved path is still inside pdf_dir.
    """
    if not name or name != os.path.basename(name) or "/" in name or "\\" in name:
        return None
    if name in (".", "..") or ":" in name or "\x00" in name:
        return None
    if not name.lower().endswith(".pdf"):
        return None
    base = pdf_dir.resolve()
    candidate = (base / name).resolve()
    if candidate.parent != base:
        return None
    return candidate


def save_pdf(pdf_dir: Path, name: str, stream: BinaryIO, *, max_bytes: int = MAX_PDF_BYTES) -> Path:
    """Write the upload to pdf_dir/name after validating its header and size.

    The data is written to a temporary file in the same directory first and
    moved into place only when complete, so a rejected or interrupted upload
    never leaves a partial PDF behind. Overwrites an existing file of the same
    name (re-uploading a paper's PDF replaces it).
    """
    target = resolve_pdf_path(pdf_dir, name)
    if target is None:
        raise UploadError("保存先のファイル名が不正です。")
    pdf_dir.mkdir(parents=True, exist_ok=True)

    head = stream.read(len(PDF_MAGIC))
    if not head.startswith(PDF_MAGIC):
        raise UploadError("このファイルは PDF ではないようです（中身が PDF 形式ではありません）。")

    fd, tmp_name = tempfile.mkstemp(dir=pdf_dir, suffix=".part")
    try:
        total = len(head)
        with os.fdopen(fd, "wb") as out:
            out.write(head)
            while True:
                chunk = stream.read(_CHUNK)
                if not chunk:
                    break
                total += len(chunk)
                if total > max_bytes:
                    raise UploadError(
                        f"ファイルが大きすぎます（上限 {max_bytes // (1024 * 1024)} MB）。"
                    )
                out.write(chunk)
        os.replace(tmp_name, target)
    except BaseException:
        if os.path.exists(tmp_name):
            os.unlink(tmp_name)
        raise
    return target
